def load_name_dict(path: Path | None = None) -> dict[str, str]:
    if path is None:
        path = _BUNDLED_NAME_DICT_PATH
    text = path.read_text(encoding="utf-8").strip()
    if not text:
        return {}
    if path.suffix.lower() == ".json":
        raw = json.loads(text)
        return {str(k): str(v) for k, v in raw.items()}

    mapping: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "," in line:
            k, v = line.split(",", 1)
        elif "=" in line:
            k, v = line.split("=", 1)
        else:
            continue
        mapping[k.strip()] = v.strip()
    return mapping


def rule_based_name(token: str) -> str:
    parts = re.findall(r"[A-Z]+(?=[A-Z][a-z]|\b)|[A-Z]?[a-z]+|\d+", token)
    if not parts:
        return token
    return " ".join(parts)


def _split_identifier(name: str) -> list[str]:
    normalized = re.sub(r"[/_\-\.]+", " ", name)
    parts: list[str] = []
    for raw in normalized.split():
        sub = re.findall(r"[A-Z]+(?=[A-Z][a-z]|\b)|[A-Z]?[a-z]+|\d+", raw)
        if sub:
            parts.extend(sub)
        else:
            parts.append(raw)
    return [p for p in parts if p]


def koreanize_identifier(name: str) -> str:
    token_map = _effective_token_map()
    simple = (name or "").strip()
    if re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", simple):
        direct = token_map.get(simple.lower())
        if direct:
            return direct

    parts = _split_identifier(name)
    if not parts:
        return name
    mapped: list[str] = []
    i = 0
    while i < len(parts):
        if i + 1 < len(parts):
            two = f"{parts[i]}{parts[i + 1]}".lower()
            if two in token_map:
                mapped.append(token_map[two])
                i += 2
                continue
        mapped.append(token_map.get(parts[i].lower(), parts[i]))
        i += 1
    return " ".join(mapped)


def resolve_name(
    name_en: str,
    name_dict: dict[str, str],
    template_reuse: str | None,
    *,
    prefer_korean: bool = False,
) -> tuple[str, bool]:
    if name_en in name_dict:
        return name_dict[name_en], True
    if template_reuse:
        return template_reuse, True
    if prefer_korean:
        ko = koreanize_identifier(name_en)
        if ko != name_en:
            return ko, True
    fallback = rule_based_name(name_en)
    if fallback == name_en:
        return name_en, False
    return fallback, True
