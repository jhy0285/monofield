  const { project } = await imported.json() as { project: { id: string; metadata: Record<string, unknown> } };
  const changed = await page.request.patch(`/api/projects/${project.id}`, { data: { metadata: { ...project.metadata, workMode: 'development' } } }); expect(changed.ok()).toBeTruthy();
  const config = { mode: 'daemon', onboardingCompleted: true, privacyDecisionAt: 1, telemetry: { metrics: false, content: false, artifactManifest: false }, skillId: null, designSystemId: null };
  await page.request.put('/api/app-config', { data: config });
  await page.addInitScript(saved => {
    localStorage.setItem('open-design:config', JSON.stringify(saved)); localStorage.setItem('open-design:locale', 'ko'); localStorage.setItem('open-design:locale-source', 'manual');
    localStorage.setItem('monofield:development-workspace-tutorial:v2', 'done');
  }, config);
  await page.goto(`/projects/${project.id}`);
  await expect(page.getByTestId('development-open-changes')).toBeVisible({ timeout: T.xlong });
  await page.getByTestId('development-open-changes').click();
  const panel = page.getByRole('region', { name: '코드에서 온톨로지 구축' }); await expect(panel).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('01-code-only-entry.png'), fullPage: true });
  await panel.getByRole('button', { name: '코드에서 온톨로지 구축' }).click();
  const demo = page.getByRole('dialog', { name: '코드에서 관계와 영향 찾기' });
  await expect(demo).toBeVisible();
  await demo.getByRole('button', { name: '일시 정지', exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath('tutorial-01-code-scope.png'), fullPage: true, animations: 'disabled' });
  await demo.getByRole('button', { name: '업무 문서도 제공', exact: true }).click();
  await expect(demo).toContainText('20초');
  await page.screenshot({ path: testInfo.outputPath('tutorial-02-business-context.png'), fullPage: true, animations: 'disabled' });
  await expect(panel.getByLabel('선택 비즈니스 문서 (모듈 기준 Markdown/TXT 경로, 한 줄에 하나)')).toHaveValue('');
  await demo.getByRole('button', { name: '4 / 5 단계', exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath('tutorial-03-change-impact.png'), fullPage: true, animations: 'disabled' });
  await demo.getByRole('checkbox', { name: '다시 보지 않기' }).check();
  await demo.getByRole('button', { name: '닫기', exact: true }).click();
  await expect(demo).toBeHidden();
  await panel.getByRole('button', { name: '온톨로지 만들기 데모 보기' }).click();
  await expect(demo).toBeVisible(); await page.keyboard.press('Escape'); await expect(demo).toBeHidden();
  await expect(panel.getByText('업무 문서 미제공 · 코드 중심 초안')).toBeVisible();
  await panel.getByRole('checkbox', { name: '전체 코드베이스 분석 (프런트·백엔드 포함)' }).check();
  await panel.getByRole('button', { name: '코드로 자동 구축' }).click();
  await expect(panel).toContainText('소스 5개 중 4개 구문 분석', { timeout: T.long });
  await expect(panel).toContainText('미지원 파일 1개'); await expect(panel).toContainText('GET /api/signals');
  await expect(panel).toContainText('SignalDashboard.vue');
  await panel.getByLabel('대상과 연결 관계 확인').selectOption({ label: 'api · GET /api/signals' });
  await panel.getByText('원문 근거').first().click();
  await panel.getByLabel('대상과 연결 관계 확인').scrollIntoViewIfNeeded();
  await panel.getByText('SignalDashboard.vue · GET /api/signals → GET /api/signals').scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('02-code-facts-and-source-evidence.png'), fullPage: true });
  await panel.getByRole('button', { name: '코드로 자동 구축' }).click();
  await expect(panel).toContainText('코드가 같아 기존 그래프 재사용', { timeout: T.long });
  await page.screenshot({ path: testInfo.outputPath('03-verified-cache-reuse.png'), fullPage: true });
  await panel.getByLabel('선택 비즈니스 문서 (모듈 기준 Markdown/TXT 경로, 한 줄에 하나)').fill('business.md');
  await panel.getByRole('button', { name: '코드로 자동 구축' }).click();
  await expect(panel).toContainText('교차로 (Intersection)', { timeout: T.long });
  await expect(panel).toContainText('업무 개념 연결 후보');
  await panel.getByLabel('검색').fill('교차로');
  await panel.getByLabel('대상과 연결 관계 확인').selectOption({ label: 'concept · 교차로 (Intersection)' });
  await panel.getByText('원문 근거').first().click();
  await panel.getByLabel('대상과 연결 관계 확인').scrollIntoViewIfNeeded();
  await panel.getByText('교차로 (Intersection) → traffic.Intersection').scrollIntoViewIfNeeded();
