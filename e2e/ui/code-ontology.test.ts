  const root = join(toolsDev.root, 'scratch', 'traffic-codebase'); await mkdir(root, { recursive: true });
  await writeFile(join(root, 'package.json'), JSON.stringify({ name: 'traffic-control', private: true }));
  await writeFile(join(root, 'SignalController.java'), 'package traffic; import org.springframework.web.bind.annotation.*; @RestController @RequestMapping("/api/signals") class SignalController { private SignalService service; @GetMapping public int signals(){return service.find();} }');
  await writeFile(join(root, 'SignalService.java'), 'package traffic; public class SignalService { public int find(){return 30;} }');
  await writeFile(join(root, 'SignalDashboard.vue'), '<script setup lang="ts">import axios from "axios"; async function loadSignals(){return axios.get("/api/signals");}</script><template><button @click="loadSignals">Signals</button></template>');
  await writeFile(join(root, 'Intersection.java'), 'package traffic; import jakarta.persistence.*; @Entity @Table(name="intersections") class Intersection { int signalCycle; }');
  await writeFile(join(root, 'business.md'), '# 교차로 (Intersection)\n\n교차로의 신호 주기를 운영합니다.\n- 최소 녹색 시간: 20초\n');
  await writeFile(join(root, 'extra.py'), 'class AdditionalSensor: pass\n');
