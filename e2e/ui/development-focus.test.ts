import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createServer } from 'node:net';
import { join } from 'node:path';
import { test, expect } from '@/playwright/suite';
import { T } from '@/timeouts';

test('[P1] keeps the editor and drafts while switching tools, running a server and opening AI', async ({ page, toolsDev }, testInfo) => {
  test.setTimeout(4 * T.xlong); await page.setViewportSize({ width: 1500, height: 1000 });
  const reservation = createServer();
  await new Promise<void>(resolve => reservation.listen(0, '127.0.0.1', resolve));
  const address = reservation.address(); if (!address || typeof address === 'string') throw new Error('Missing fixture port');
  const port = address.port; await new Promise<void>((resolve, reject) => reservation.close(error => error ? reject(error) : resolve()));
  const root = join(toolsDev.root, 'scratch', 'pricing-workspace'); await mkdir(root, { recursive: true });
  const original = '/** Calculate the invoice total including tax. */\nexport function total(amount) {\n  return Math.round(amount * 1.1);\n}\n';
  const updated = original.replace('1.1', '1.2');
  await writeFile(join(root, 'pricing.js'), original);
  await writeFile(join(root, 'package.json'), JSON.stringify({ name: 'pricing-workspace', private: true, type: 'module', scripts: { dev: `node server.mjs --port ${port}` } }));
  await mkdir(join(root, 'node_modules'));
  await writeFile(join(root, 'server.mjs'), `import { createServer } from 'node:http';\nimport { total } from './pricing.js';\ncreateServer((request, response) => { response.setHeader('content-type','text/html; charset=utf-8'); response.end('<!doctype html><html lang="ko"><head><title>정산 미리보기</title></head><body style="font:18px system-ui;padding:48px;background:#fafafa"><p>MonoField · 실행 미리보기</p><h1>정산 시스템</h1><p>기준 금액 100 · 변경한 세율 20%</p><h2>합계 '+total(100)+'</h2></body></html>'); }).listen(Number(process.env.PORT || ${port}), '127.0.0.1', () => console.log('Pricing preview ready'));\n`);
  const git = (...args: string[]) => execFileSync('git', ['-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', ...args], { cwd: root });
  git('init','--quiet'); git('add','.'); git('commit','--quiet','--no-verify','-m','Legacy pricing baseline');
  const imported = await page.request.post('/api/import/folder', { data: { baseDir: root, name: '정산 시스템 · 개발 작업공간' } }); expect(imported.ok()).toBeTruthy();
  const { project } = await imported.json();
  await page.request.patch(`/api/projects/${project.id}`, { data: { metadata: { ...project.metadata, workMode: 'development', development: { autoVerify: false } } } });
  const config = { mode: 'daemon', onboardingCompleted: true, privacyDecisionAt: 1, telemetry: { metrics: false, content: false, artifactManifest: false }, skillId: null, designSystemId: null };
  await page.request.put('/api/app-config', { data: config });
  await page.addInitScript(saved => {
    localStorage.setItem('open-design:config', JSON.stringify(saved)); localStorage.setItem('open-design:locale','ko'); localStorage.setItem('open-design:locale-source','manual');
    localStorage.setItem('monofield:development-workspace-tutorial:v2','done'); localStorage.setItem('monofield:ontology-tutorial-dismissed:v1','true');
  }, config);
  await page.goto(`/projects/${project.id}`);
  await expect(page.getByTestId('development-tools-dock')).toBeVisible({ timeout: T.xlong });
  await expect(page.locator('.chat-log-wrap')).toBeHidden();
  await expect(page.getByTestId('development-tools-dock').getByRole('tabpanel')).toHaveCount(0);
  await page.getByTestId('design-file-row-pricing.js').locator('.df-row-openable').first().dblclick();
  const editor = page.getByTestId('text-editor-input'); await expect(editor).toHaveValue(original);
  const composer = page.locator('.composer-input-wrap [contenteditable="true"]');
  await composer.fill('세율 변경에 영향을 받는 코드를 확인해줘');
  await page.screenshot({ path: testInfo.outputPath('01-editor-first.png'), fullPage: true, animations: 'disabled' });
  await editor.fill(updated);
  await page.getByTestId('development-server-logs-toggle').click();
  await expect(page.getByTestId('development-server-logs')).toBeVisible();
  await expect(editor).toHaveValue(updated);
  await page.getByTestId('development-open-changes').click();
  await expect(page.getByTestId('git-changes-panel')).toBeVisible();
  await expect(editor).toHaveValue(updated);
  await page.getByTestId('text-editor-save').click();
  await expect.poll(() => readFile(join(root,'pricing.js'),'utf8')).toBe(updated);
  const changedSource = page.getByTestId('git-changes-panel').getByRole('button', { name: /pricing.js/ });
  await expect(changedSource).toBeVisible({ timeout: T.long }); await changedSource.click();
  await expect(page.getByTestId('git-changes-panel')).toContainText('1.2');
  await page.screenshot({ path: testInfo.outputPath('02-editor-and-diff.png'), fullPage: true, animations: 'disabled' });
  await page.getByTestId('development-open-terminal').click();
  const terminal = page.getByTestId('terminal-viewer'); await expect(terminal.locator('.xterm-screen')).toBeVisible({ timeout: T.long });
  await terminal.locator('.xterm-screen').click(); await page.keyboard.type("node -p '6*7'"); await page.keyboard.press('Enter');
  await expect(terminal.locator('.xterm-rows')).toContainText('42', { timeout: T.long });
  await page.screenshot({ path: testInfo.outputPath('03-editor-and-terminal.png'), fullPage: true, animations: 'disabled' });
  await page.getByTestId('development-server-logs-toggle').click();
  await expect(terminal).toBeHidden(); await expect(editor).toHaveValue(updated);
  await page.getByTestId('development-open-terminal').click(); await expect(terminal.locator('.xterm-rows')).toContainText('42');
  await page.getByTestId('development-expand-chat').click(); await expect(page.locator('.chat-log-wrap')).toBeVisible();
  await expect(composer).toContainText('세율 변경에 영향을 받는 코드를 확인해줘');
  await page.getByTestId('workspace-focus-toggle').click(); await expect(page.locator('.chat-log-wrap')).toBeHidden();
  await expect(composer).toContainText('세율 변경에 영향을 받는 코드를 확인해줘');
  await page.getByRole('button', { name: '하단 도구 닫기', exact: true }).click();
  await expect(editor).toHaveValue(updated); await expect(terminal).toBeHidden();
  await page.getByTestId('development-run-action').click();
  try {
    await expect(page.getByTestId('development-open-browser')).toBeVisible({ timeout: T.long });
    await page.getByTestId('development-server-logs-toggle').click(); await expect(page.getByTestId('development-server-logs')).toContainText('Pricing preview ready');
    await page.screenshot({ path: testInfo.outputPath('04-editor-and-run-logs.png'), fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: '하단 도구 닫기', exact: true }).click();
    await page.getByTestId('development-open-browser').click();
    await expect(page.frameLocator('.db-fallback iframe').getByRole('heading', { name: '합계 120' })).toBeVisible({ timeout: T.long });
    await page.screenshot({ path: testInfo.outputPath('05-running-preview.png'), fullPage: true, animations: 'disabled' });
    await page.setViewportSize({ width: 1000, height: 800 });
    await expect(page.getByTestId('development-tools-dock')).toBeVisible();
    expect(await page.locator('body').evaluate(body => body.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath('06-narrow-workspace.png'), fullPage: true, animations: 'disabled' });
  } finally {
    await page.request.post(`/api/projects/${project.id}/development/server/stop`, { data: {} });
  }
});
